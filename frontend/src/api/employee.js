import { api, downloadFile, openFile } from './client';

export const employeeApi = {
  context: () => api.get('/me/context'),
  payslips: () => api.get('/me/payslips'),
  downloadPayslip: (id) => downloadFile(`/me/payslips/${id}/pdf`),
  leaveTypes: () => api.get('/me/leave/types'),
  leaveBalances: (year) => api.get(`/me/leave/balances${year ? `?year=${year}` : ''}`),
  leaveApplications: () => api.get('/me/leave/applications'),
  applyLeave: (data) => api.post('/me/leave/applications', data),
  cancelLeave: (id) => api.post(`/me/leave/applications/${id}/cancel`, {}),
  policy: () => api.get('/me/policy'),
  acknowledgePolicy: (version) => api.post('/me/policy/acknowledge', { version }),
  calendar: (year, month) => api.get(`/me/calendar?${new URLSearchParams({ year, month })}`),
  workplace: () => api.get('/me/workplace'),
  time: (year, month) => api.get(`/me/time?${new URLSearchParams({ year, month })}`),
  checkIn: () => api.post('/me/time/check-in', {}),
  checkOut: () => api.post('/me/time/check-out', {}),
  expenses: () => api.get('/me/expenses'),
  submitExpense: (data) => api.post('/me/expenses', data),
  withdrawExpense: (id) => api.post(`/me/expenses/${id}/withdraw`, {}),
  openExpenseReceipt: (id) => openFile(`/me/expenses/${id}/receipt`),
  devices: () => api.get('/me/devices'),
  startDeviceLink: (currentPassword) => api.post('/me/devices/link', { currentPassword }),
  deviceLink: (id) => api.get(`/me/devices/link/${id}`),
  approveDeviceLink: (id, verificationCode) => api.post(`/me/devices/link/${id}/approve`, { verificationCode }),
  denyDeviceLink: (id) => api.post(`/me/devices/link/${id}/deny`, {}),
  cancelDeviceLink: (id) => api.post(`/me/devices/link/${id}/cancel`, {}),
  revokeDevice: (id) => api.post(`/me/devices/${id}/revoke`, {}),
};

export const employeeAdminApi = {
  policy: () => api.get('/org/employee-policy'),
  publishPolicy: (data) => api.post('/org/employee-policy', data),
  holidays: () => api.get('/org/holidays'),
  createHoliday: (data) => api.post('/org/holidays', data),
  updateHoliday: (id, data) => api.put(`/org/holidays/${id}`, data),
  time: (year, month) => api.get(`/org/time?${new URLSearchParams({ year, month })}`),
  correctTime: (id, data) => api.put(`/org/time/${id}/correct`, data),
  expenses: () => api.get('/org/expenses'),
  prepareExpense: (id) => api.post(`/org/expenses/${id}/prepare`, {}),
  decideExpense: (id, decision, reason) => api.post(`/org/expenses/${id}/decide`, { decision, reason }),
  payExpense: (id, paymentReference, paidAt) => api.post(`/org/expenses/${id}/pay`, { paymentReference, paidAt }),
  openExpenseReceipt: (id) => openFile(`/org/expenses/${id}/receipt`),
};
